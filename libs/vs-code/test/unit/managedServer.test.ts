function enoent(target: string): Error {
    return Object.assign(new Error(`ENOENT: ${target}`), { code: 'ENOENT' });
}

/** A filesystem in memory, recording every write and removal in order. */
class FakeFs implements ManagedFs {
    readonly files = new Map<string, Buffer>();
    readonly dirs = new Set<string>();
    readonly modes = new Map<string, number>();
    readonly events: string[] = [];

    private under(target: string, root: string): boolean {
        return target === root || target.startsWith(`${root}/`);
    }

    async readFile(file: string): Promise<string> {
        const data = this.files.get(file);
        if (!data) {
            throw enoent(file);
        }
        return data.toString('utf8');
    }

    async writeFile(file: string, data: string | Buffer, mode?: number): Promise<void> {
        this.files.set(file, Buffer.isBuffer(data) ? data : Buffer.from(data, 'utf8'));
        if (mode !== undefined) {
            this.modes.set(file, mode);
        }
        this.events.push(`write ${file}`);
    }

    async mkdir(dir: string, recursive: boolean): Promise<void> {
        if (!recursive && this.dirs.has(dir)) {
            throw Object.assign(new Error(`EEXIST: ${dir}`), { code: 'EEXIST' });
        }
        this.dirs.add(dir);
    }

    async rm(target: string): Promise<void> {
        this.events.push(`rm ${target}`);
        for (const file of [...this.files.keys()]) {
            if (this.under(file, target)) {
                this.files.delete(file);
            }
        }
        for (const dir of [...this.dirs]) {
            if (this.under(dir, target)) {
                this.dirs.delete(dir);
            }
        }
    }

    async rename(from: string, to: string): Promise<void> {
        this.events.push(`rename ${from} -> ${to}`);
        for (const [file, data] of [...this.files]) {
            if (this.under(file, from)) {
                this.files.delete(file);
                this.files.set(to + file.slice(from.length), data);
            }
        }
        for (const dir of [...this.dirs]) {
            if (this.under(dir, from)) {
                this.dirs.delete(dir);
                this.dirs.add(to + dir.slice(from.length));
            }
        }
    }

    async readdir(dir: string): Promise<string[]> {
        const names = new Set<string>();
        for (const entry of [...this.files.keys(), ...this.dirs]) {
            if (entry.startsWith(`${dir}/`)) {
                names.add(entry.slice(dir.length + 1).split('/')[0]);
            }
        }
        return [...names].sort();
    }

    async exists(target: string): Promise<boolean> {
        return this.files.has(target) || this.dirs.has(target)
            || [...this.files.keys()].some(file => file.startsWith(`${target}/`));
    }
}

