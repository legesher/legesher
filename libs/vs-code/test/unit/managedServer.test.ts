interface Harness {
    deps: ManagedServerDeps;
    fs: FakeFs;
    runs: { command: string; args: readonly string[]; env: NodeJS.ProcessEnv; cwd: string }[];
    downloads: string[];
    sleeps: number[];
    clock: { now: number };
    /** The heartbeat callbacks still registered; `beat()` runs them all. */
    ticks: Set<() => void>;
    beat(): Promise<void>;
    alive: Set<number>;
}

/**
 * Deps whose `run` behaves like uv and the installed server: `uv venv` makes
 * the environment, `uv pip install` puts the server in it, and the server
 * answers `--version` with `reports`.
 */
function harness(options: {
    reports?: string;
    failPip?: string;
    uvVersion?: string;
    env?: NodeJS.ProcessEnv;
    /** The installed server fails to start, as a quarantined executable would. */
    serverBroken?: () => boolean;
    onSleep?(h: Harness): void;
} = {}): Harness {
    const fsFake = new FakeFs();
    const lock = parseServerLock(lockText());
    const h: Harness = {
        fs: fsFake,
        runs: [],
        downloads: [],
        sleeps: [],
        clock: { now: 1_000_000 },
        ticks: new Set(),
        beat: async () => {
            for (const tick of [...h.ticks]) {
                tick();
            }
            await new Promise(resolve => setImmediate(resolve));
        },
        alive: new Set([4242]),
        deps: undefined as unknown as ManagedServerDeps,
    };
    h.deps = {
        platform: 'linux',
        env: options.env ?? { PATH: '/usr/bin', HOME: '/home/देवनागरी ශ්‍රී' },
        download: async url => {
            h.downloads.push(url);
            return UV_ARCHIVE;
        },
        run: async (command, args, runOptions) => {
            h.runs.push({ command, args, env: runOptions.env, cwd: runOptions.cwd });
            // On the same timeline as the writes, so order can be asserted.
            fsFake.events.push(`run ${command} ${args.join(' ')}`);
            if (command === layout.uvPath && args[0] === '--version') {
                return { stdout: `uv ${options.uvVersion ?? UV_VERSION} (abc 2026-11-03)\n`, stderr: '' };
            }
            if (command === layout.uvPath && args[0] === 'venv') {
                await fsFake.mkdir(args[args.length - 1], true);
                await fsFake.writeFile(layout.envPython(lock.id), 'python');
                return { stdout: '', stderr: 'Using CPython 3.12.16\n' };
            }
            if (command === layout.uvPath && args[0] === 'pip') {
                if (options.failPip) {
                    throw new Error(options.failPip);
                }
                await fsFake.writeFile(layout.serverPath(lock.id), 'server');
                return { stdout: '', stderr: 'Installed 40 packages\n' };
            }
            if (command === layout.serverPath(lock.id) && args[0] === '--version') {
                if (options.serverBroken?.()) {
                    throw new Error('Access is denied.');
                }
                return { stdout: `${options.reports ?? 'legesher-lsp 0.3.0'}\n`, stderr: '' };
            }
            throw new Error(`unexpected run: ${command} ${args.join(' ')}`);
        },
        fs: fsFake,
        now: () => h.clock.now,
        sleep: async ms => {
            h.sleeps.push(ms);
            h.clock.now += ms;
            options.onSleep?.(h);
        },
        every: (_ms, tick) => {
            h.ticks.add(tick);
            return () => h.ticks.delete(tick);
        },
        pid: 4242,
        isAlive: pid => h.alive.has(pid),
        log: () => undefined,
    };
    return h;
}

function request(target: UvTarget = TARGET) {
    return { layout, lock: parseServerLock(lockText()), lockPath: LOCK_PATH, target, platformKey: 'linux-x64' };
}

