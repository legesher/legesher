"""The first-run path: ``legesher init``, then every command that reads its config.

``init`` used to write a config shape nothing else read, so the language it
was asked for fell back to English everywhere: ``legesher config get
language`` exited 1, ``legesher git status`` reported ``en``, the clean
filter left stray keywords as typed, and ``legesher run`` failed with a
``SyntaxError``. These tests walk that path in each order a new user might
try it, and keep a config file already on disk in the old shape working.

``init``, ``config`` and ``git`` run in process against real git
repositories. ``run`` is a subprocess, because the hooks it installs are
process-wide.

On CPython 3.10 and 3.11 the pure-Python tokenizer cannot read some of these
scripts (``tests/interpreter_gaps.py``, gap 1), so the cases that run a
program or put one through the filter are strict xfails there, decided from
the program's own bytes.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path
from unittest.mock import patch

import pytest
import yaml
from click.testing import CliRunner
from legesher_core import TokenTranslator
from legesher_i18n.language_registry import get_active_language_codes

from legesher.cli.main import cli
from legesher.config import LegesherConfig
from tests.interpreter_gaps import xfail_if_return_hop_is_inert

#: The console script's body (see test_cli_run.py for why not ``-m``).
CLI = "from legesher.cli.main import cli; cli()"

#: One program per script: ``(language, a name, the text it prints)``. The
#: name is an identifier in the language's own script, with combining marks
#: wherever the script has them; the text is what must reach stdout byte for
#: byte. Spanish is the reported case and proves nothing about Unicode.
PROGRAMS = [
    pytest.param("es", "saludar", "¡Hola, Mundo!", id="es-latin"),
    pytest.param("ar", "مَرْحَبًا", "مَرْحَبًا بِالعَالَمِ", id="ar-vocalised"),
    pytest.param("he", "שָׁלוֹם", "שָׁלוֹם עוֹלָם", id="he-pointed"),
    pytest.param("hi", "नमस्ते", "नमस्ते दुनिया", id="hi-devanagari"),
    # A ZWJ is not legal inside a Python name, so the conjunct is in the text.
    pytest.param("si", "ආයුබෝවන්", "ශ්\u200dරී ලංකාව", id="si-zwj"),
    pytest.param("th", "สวัสดี", "สวัสดีชาวโลก", id="th-thai"),
    pytest.param("zh", "你好", "你好，世界", id="zh-cjk"),
]

ENGLISH = 'def {name}(x):\n    return x\n\nprint({name}("{text}"))\n'

#: Three lines with a keyword each, for the clean filter: written in a
#: language with the middle line left in English, it is stored whole in the
#: language.
STRAY = "def {name}(x):\n    if x:\n        return x\n"

#: What ``legesher init`` wrote up to 0.25.1, byte for byte, for one language.
