class TestRunSaysWhichLanguageItUsed:
    """A script that does not compile is reported as CPython reports it,
    followed by the language it was read as and how to name another."""

    def test_no_configuration(self, project):
        script = write_program(project, "hi", "नमस्ते", "नमस्ते दुनिया")
        result = run_script(script)
        stderr = result.stderr.decode("utf-8")
        assert result.returncode == 1
        assert stderr.splitlines()[0].startswith(f'  File "{script}"')
        assert "SyntaxError" in stderr
        assert "Traceback" not in stderr
        note = stderr[stderr.index("legesher:") :]
        assert "English (en)" in note
        assert "--lang" in note and "legesher init" in note

    def test_a_configured_language_is_named_with_its_file(self, repo):
        legesher("init", "-l", "es", "-p", "3.13", "--no-git", "--no-ai-context")
