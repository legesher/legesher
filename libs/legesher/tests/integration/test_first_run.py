"""The first-run path: ``legesher init``, then every command that reads its config.

``init`` used to write a config shape nothing else read, so the language it
was asked for fell back to English everywhere: ``legesher config get
language`` exited 1, ``legesher git status`` reported ``en``, the clean
filter left stray keywords as typed, and ``legesher run`` failed with a
``SyntaxError``. These tests walk that path in each order a new user might
try it, and keep a config file already on disk in the old shape working.

``init``, ``config`` and ``git`` run in process against real git
repositories. ``run`` is a subprocess, because the hooks it installs are
process-wide.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest
import yaml
from click.testing import CliRunner
from legesher_core import TokenTranslator
from legesher_i18n.language_registry import get_active_language_codes

from legesher.cli.main import cli
from legesher.config import LegesherConfig, get_language_for_git_filter

#: The console script's body (see test_cli_run.py for why not ``-m``).
CLI = "from legesher.cli.main import cli; cli()"

#: One program per script: ``(language, a name, the text it prints)``. The
#: name is an identifier in the language's own script, with combining marks
#: wherever the script has them; the text is what must reach stdout byte for
#: byte. Spanish is the reported case and proves nothing about Unicode.
PROGRAMS = [
    pytest.param("es", "saludar", "¡Hola, Mundo!", id="es-latin"),
    pytest.param("ar", "مَرْحَبًا", "مَرْحَبًا بِالعَالَمِ", id="ar-vocalised"),
    pytest.param("he", "שָׁלוֹם", "שָׁלוֹם עוֹלָם", id="he-pointed"),
    pytest.param("hi", "नमस्ते", "नमस्ते दुनिया", id="hi-devanagari"),
    # A ZWJ is not legal inside a Python name, so the conjunct is in the text.
    pytest.param("si", "ආයුබෝවන්", "ශ්\u200dරී ලංකාව", id="si-zwj"),
    pytest.param("th", "สวัสดี", "สวัสดีชาวโลก", id="th-thai"),
    pytest.param("zh", "你好", "你好，世界", id="zh-cjk"),
]

ENGLISH = 'def {name}(x):\n    return x\n\nprint({name}("{text}"))\n'

#: What ``legesher init`` wrote up to 0.25.1, byte for byte, for one language.
OLD_INIT_CONFIG = """\
# Legesher Configuration
# Generated by: legesher init
# Documentation: https://docs.legesher.io

# Languages enabled in this project
languages:
  - {lang}

# Python version for language pack compatibility
python_version: "3.13"

# Git integration (each file is stored in its author's language)
git:
  enabled: true
  canonical_language: "en"

# AI assistant context generation
ai_context:
  enabled: false
  context_files:
    - AI-CONTEXT-{lang}.md

# Translation preferences
translation:
  # Default source language (for ambiguous cases)
  default_source: "en"

  # Default target language (for CLI commands)
  default_target: "{lang}"

  # Preserve comments during translation
  preserve_comments: true

  # Preserve string literals during translation
  preserve_strings: true

# Editor integration
editor:
  # Enable LSP hover context enrichment
  lsp_hover: true

  # Enable inline completion context injection
  inline_completion: true

  # Show bilingual tooltips
  bilingual_tooltips: true
"""


@pytest.fixture(autouse=True)
def isolated_home(tmp_path_factory, monkeypatch):
    """No test reads the developer's own ``~/.legesher`` or git config."""
    home = tmp_path_factory.mktemp("home")
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setenv("USERPROFILE", str(home))  # Path.home() on Windows
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", str(home / "gitconfig"))
    monkeypatch.setenv("GIT_CONFIG_NOSYSTEM", "1")
    return home


def git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", *args], cwd=repo, capture_output=True, text=True, check=True
    )


@pytest.fixture
def project(tmp_path, monkeypatch) -> Path:
    """An empty directory that is not a git repository."""
    root = tmp_path / "proyecto"
    root.mkdir()
    monkeypatch.chdir(root)
    return root


@pytest.fixture
def repo(project) -> Path:
    """An empty git repository."""
    git(project, "init", "-q")
    git(project, "config", "user.email", "test@example.com")
    git(project, "config", "user.name", "Test")
    return project


def legesher(*args: str, ok: bool = True):
    result = CliRunner().invoke(cli, list(args), input="")
    if ok:
        assert result.exit_code == 0, result.output
    return result


def write_program(root: Path, lang: str, name: str, text: str) -> Path:
    """``ENGLISH`` in ``lang``'s keywords; it must not compile as English."""
    source = TokenTranslator.from_language_pack(lang).translate_code(
        ENGLISH.format(name=name, text=text)
    )
    with pytest.raises(SyntaxError):
        compile(source, "programa.py", "exec")
    script = root / "programa.py"
    script.write_text(source, encoding="utf-8")
    return script


def run_script(script: Path, *args: str, cwd: Path | None = None):
    """``legesher run`` in a subprocess; stdout and stderr as bytes."""
    env = {**os.environ, "PYTHONIOENCODING": "utf-8"}
    return subprocess.run(
        [sys.executable, "-c", CLI, "run", str(script), *args],
        capture_output=True,
        cwd=cwd or script.parent,
        env=env,
        check=False,
    )


def config_file(root: Path) -> Path:
    return root / ".legesher" / "config.yml"


def read_config(root: Path) -> dict:
    return yaml.safe_load(config_file(root).read_text(encoding="utf-8"))


def assert_every_reader_agrees(root: Path, lang: str) -> None:
    """``config get``, ``git status``, the filter's lookup and the loader."""
    assert legesher("config", "get", "language").output.strip() == lang
    assert f"Language: {lang}\n" in legesher("git", "status").output
    assert get_language_for_git_filter() == lang
    assert LegesherConfig.load().language == lang


def assert_runs(script: Path, text: str, **kwargs) -> None:
    result = run_script(script, **kwargs)
    assert result.returncode == 0, result.stderr.decode("utf-8", "replace")
    assert result.stdout == (text + os.linesep).encode("utf-8")


class TestRunStraightAfterInit:
    """The definition of done: every reader agrees with what init was asked."""

    @pytest.mark.parametrize(("lang", "name", "text"), PROGRAMS)
    def test_with_git(self, repo, lang, name, text):
        script = write_program(repo, lang, name, text)
        legesher("init", "-l", lang, "-p", "3.13", "--git", "--no-ai-context")
        assert_every_reader_agrees(repo, lang)
        assert_runs(script, text)

    @pytest.mark.parametrize(("lang", "name", "text"), PROGRAMS)
    def test_outside_a_git_repository(self, project, lang, name, text):
        script = write_program(project, lang, name, text)
        legesher("init", "-l", lang, "-p", "3.13", "--no-git", "--no-ai-context")
        assert legesher("config", "get", "language").output.strip() == lang
        assert LegesherConfig.load().language == lang
        assert_runs(script, text)

    def test_from_a_subdirectory(self, project):
        legesher("init", "-l", "hi", "-p", "3.13", "--no-git", "--no-ai-context")
        package = project / "पैकेज"
        package.mkdir()
        script = write_program(package, "hi", "नमस्ते", "नमस्ते दुनिया")
        assert_runs(script, "नमस्ते दुनिया", cwd=package)

    @pytest.mark.parametrize("lang", sorted(get_active_language_codes()))
    def test_every_language_is_read_back(self, project, lang):
        legesher("init", "-l", lang, "-p", "3.13", "--no-git", "--no-ai-context")
        assert legesher("config", "get", "language").output.strip() == lang
        assert LegesherConfig.load().language == lang

    def test_the_clean_filter_knows_the_language(self, repo, monkeypatch):
        bin_dir = os.path.dirname(sys.executable)
        monkeypatch.setenv("PATH", bin_dir + os.pathsep + os.environ.get("PATH", ""))
        legesher("init", "-l", "es", "-p", "3.13", "--git", "--no-ai-context")
        (repo / "m.py").write_text("definir f(x):\n    if x:\n        devolver 1\n")
        git(repo, "add", "m.py")
        assert git(repo, "show", ":0:m.py").stdout == (
            "definir f(x):\n    si x:\n        devolver 1\n"
        )


class TestWhatInitWrites:
    def test_the_shape_every_reader_shares(self, project):
        legesher("init", "-l", "ar", "-p", "3.12", "--no-git", "--no-ai-context")
        assert read_config(project) == {
            "language": "ar",
            "languages": ["ar"],
            "python_version": "3.12",
            "git": {"canonical_language": "en", "filter_enabled": False},
            "metadata": {
                "enabled": True,
                "directory": ".legesher/metadata",
                "track_in_git": True,
                "verbose_history": False,
                "max_history_entries": 100,
            },
        }

    def test_the_first_language_is_the_working_one(self, project):
        result = legesher(
            "init", "-l", "th", "-l", "he", "-p", "3.13", "--no-git", "--no-ai-context"
        )
        data = read_config(project)
        assert data["language"] == "th"
        assert data["languages"] == ["th", "he"]
        assert "legesher config set language" in result.output

    def test_git_records_that_the_filter_is_on(self, repo):
        legesher("init", "-l", "es", "-p", "3.13", "--git", "--no-ai-context")
        assert read_config(repo)["git"]["filter_enabled"] is True

    def test_it_is_the_file_git_setup_writes(self, repo):
        legesher("init", "-l", "es", "-p", "3.13", "--git", "--no-ai-context")
        from_init = read_config(repo)
        config_file(repo).unlink()
        legesher("git", "setup", "--language", "es", "--python-version", "3.13")
        from_setup = read_config(repo)
        from_init.pop("languages")
        assert from_init == from_setup


class TestEitherOrder:
    def test_git_setup_after_init_keeps_what_init_wrote(self, repo):
        script = write_program(repo, "he", "שָׁלוֹם", "שָׁלוֹם עוֹלָם")
        legesher(
            "init", "-l", "he", "-l", "ar", "-p", "3.13", "--no-git", "--no-ai-context"
        )
        legesher("git", "setup", "--language", "he")
        data = read_config(repo)
        assert data["python_version"] == "3.13"
        assert data["languages"] == ["he", "ar"]
        assert data["git"]["filter_enabled"] is True
        assert_every_reader_agrees(repo, "he")
        assert_runs(script, "שָׁלוֹם עוֹלָם")

    def test_git_setup_with_a_new_language_adds_it_to_the_record(self, repo):
        legesher("init", "-l", "es", "-p", "3.13", "--no-git", "--no-ai-context")
        legesher("git", "setup", "--language", "zh")
        data = read_config(repo)
        assert data["language"] == "zh"
        assert data["languages"] == ["es", "zh"]

    def test_git_setup_keeps_settings_it_was_not_given(self, repo):
        legesher("git", "setup", "--language", "es", "--python-version", "3.12")
        legesher("config", "set", "metadata.max_history_entries", "7")
        legesher("config", "set", "runtime.cache_size", "64")
        legesher("config", "set", "equipo.nombre", "लेगेशर")
        legesher("git", "setup", "--language", "ar")
        data = read_config(repo)
        assert data["language"] == "ar"
        assert data["python_version"] == "3.12"
        assert data["metadata"]["max_history_entries"] == 7
        assert data["runtime"] == {"cache_size": 64}
        assert data["equipo"] == {"nombre": "लेगेशर"}

    def test_init_after_git_setup(self, repo):
        script = write_program(repo, "th", "สวัสดี", "สวัสดีชาวโลก")
        legesher("git", "setup", "--language", "th")
        refused = legesher(
            "init", "-l", "th", "-p", "3.13", "--git", "--no-ai-context", ok=False
        )
        assert refused.exit_code == 1 and "--force" in refused.output
        assert_every_reader_agrees(repo, "th")
        legesher("init", "-l", "th", "-p", "3.13", "--git", "--no-ai-context", "-f")
        assert_every_reader_agrees(repo, "th")
        assert_runs(script, "สวัสดีชาวโลก")


class TestAConfigAlreadyOnDisk:
    """A file ``init`` wrote before this change keeps working, untouched."""

    @pytest.mark.parametrize(("lang", "name", "text"), PROGRAMS)
    def test_the_old_init_shape_is_read(self, repo, lang, name, text):
        script = write_program(repo, lang, name, text)
        config_file(repo).parent.mkdir()
        old = OLD_INIT_CONFIG.format(lang=lang).encode("utf-8")
        config_file(repo).write_bytes(old)
        assert_every_reader_agrees(repo, lang)
        assert_runs(script, text)
        assert legesher("config", "get", "git.filter_enabled").output.strip() == "true"
        assert legesher("config", "get", "languages").output.strip() == lang
        # Reading never rewrites the user's file.
        assert config_file(repo).read_bytes() == old

    def test_git_setup_strips_nothing_from_it(self, repo):
        config_file(repo).parent.mkdir()
        config_file(repo).write_text(
            OLD_INIT_CONFIG.format(lang="es"), encoding="utf-8"
        )
        before = read_config(repo)
        legesher("git", "setup", "--language", "es")
        after = read_config(repo)
        for section in ("languages", "ai_context", "translation", "editor"):
            assert after[section] == before[section]
        assert after["git"]["enabled"] is True
        assert after["python_version"] == "3.13"
        assert after["language"] == "es"
        assert after["git"]["filter_enabled"] is True

    def test_an_explicit_language_wins_over_the_list(self, repo):
        config_file(repo).parent.mkdir()
        config_file(repo).write_text(
            OLD_INIT_CONFIG.format(lang="es"), encoding="utf-8"
        )
        legesher("config", "set", "language", "ar")
        assert_every_reader_agrees(repo, "ar")
        assert read_config(repo)["languages"] == ["es"]

    def test_a_filter_switched_off_stays_off(self, repo):
        config_file(repo).parent.mkdir()
        config_file(repo).write_text(
            OLD_INIT_CONFIG.format(lang="es").replace("enabled: true", "enabled: false")
        )
        assert "Filters enabled: False" in legesher("git", "status").output

    @pytest.mark.parametrize(
        "languages",
        ["languages: []", "languages: es", "languages:\n  - 7", "languages:\n  - ''"],
        ids=["empty", "scalar", "number", "blank"],
    )
    def test_a_list_that_names_no_language_is_not_one(self, repo, languages):
        config_file(repo).parent.mkdir()
        config_file(repo).write_text(languages + "\n", encoding="utf-8")
        assert LegesherConfig.load().language == "en"
        missing = legesher("config", "get", "language", ok=False)
        assert missing.exit_code == 1


class TestRunSaysWhichLanguageItUsed:
    """A script that does not compile is reported as CPython reports it,
    followed by the language it was read as and how to name another."""

    def test_no_configuration(self, project):
        script = write_program(project, "hi", "नमस्ते", "नमस्ते दुनिया")
        result = run_script(script)
        stderr = result.stderr.decode("utf-8")
        assert result.returncode == 1
        assert stderr.splitlines()[0].startswith(f'  File "{script}"')
        assert "SyntaxError" in stderr
        assert "Traceback" not in stderr
        note = stderr[stderr.index("legesher:") :]
        assert "English (en)" in note
        assert "--lang" in note and "legesher init" in note

    def test_a_configured_language_is_named_with_its_file(self, repo):
        legesher("init", "-l", "es", "-p", "3.13", "--no-git", "--no-ai-context")
        script = write_program(repo, "ar", "مَرْحَبًا", "مَرْحَبًا بِالعَالَمِ")
        result = run_script(script)
        stderr = result.stderr.decode("utf-8")
        assert result.returncode == 1
        note = stderr[stderr.index("legesher:") :]
        assert "'es'" in note
        assert os.path.join(".legesher", "config.yml") in note
        assert "--lang" in note

    def test_an_explicit_language_gets_no_note(self, project):
        script = write_program(project, "hi", "नमस्ते", "नमस्ते दुनिया")
        result = run_script(script, "--lang", "es")
        assert result.returncode == 1
        assert b"legesher:" not in result.stderr

    def test_an_error_while_running_gets_no_note(self, project):
        script = project / "programa.py"
        script.write_text("print(1 / 0)\n", encoding="utf-8")
        result = run_script(script)
        assert result.returncode == 1
        assert b"ZeroDivisionError" in result.stderr
        assert b"legesher:" not in result.stderr
