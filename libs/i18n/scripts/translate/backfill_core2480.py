"""CORE-2480: select the Xhosa (xh) Python vocabulary, DB-first.

Xhosa had a ``languages`` row and only 67 community candidates from the
2025-11-11 bulk import (31 keywords, 27 builtin functions, 9 builtin types),
the thinnest of the CORE-2181 languages, with no selection and no exception,
special-constant or implicit-parameter rows. This script decides all 184
terms of the shipped inventory, through ``backfill_common.py``.

  * A community candidate is kept where it is the right Xhosa word; it is
    lowercased where it was capitalised, and replaced, with the reason in its
    rationale, where it is wrong in sense or form. The replaced candidate
    stays in the pool.
  * Generated values are written as a linguist would choose them (noun class
    and concord, vowel coalescence, transitivity, register), following
    ``style-guides/xh.yml``. Xhosa computing vocabulary is thin, so many are
    marked ``low`` for native review. Prompts were rendered through the
    pipeline's own PromptBuilder; the selections are ``source='claude'`` at
    the experimental rung.
  * Seeds keep their word boundaries (``impazamo_yexabiso``). The shipped
    value runs the words together (``impazamoyexabiso``), and the database
    keeps the separated form as a candidate row and in each rationale.
  * Two calls are flags, both sides prepared:

      --verbs imperative|infinitive   the bare stem (vula), as Swahili, or
                                      the uku- infinitive (ukuvula)
      --joiner none|underscore        words run together, or joined with
                                      underscores

Usage:
    uv run python libs/i18n/scripts/translate/backfill_core2480.py [--dry-run]
        [--db PATH] [--verbs imperative] [--joiner none]
"""

