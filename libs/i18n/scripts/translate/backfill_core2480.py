FLAG_CHOICES = {
    "verbs": ("imperative", "infinitive"),
    "joiner": ("none", "underscore"),
}
DEFAULTS = {flag: choices[0] for flag, choices in FLAG_CHOICES.items()}

#: Word types written as a bare stem, which take uku- in the infinitive.
VERB_TYPES = {"verb", "verb phrase"}

#: Verb-typed values that are already inflected (a stative, a negative, a
#: perfect), so uku- does not apply.
INFLECTED = {"iyabizeka", "akuphunyezwanga", "ilandelelanisiwe", "inophawu"}


def separated(word_type: str, seed: str, verbs: str) -> str:
    """The value with its word boundaries, after the verb-form flag."""
    if verbs == "infinitive" and word_type in VERB_TYPES and seed not in INFLECTED:
        if seed.startswith("__") and seed.endswith("__"):
            return "__uku" + seed[2:]  # the prefix goes inside the dunder
        if seed[:1] == "y" and seed[1:2] in ("a", "e", "o"):
            # A vowel-initial verb takes y- only in the imperative (yahlula);
            # the infinitive drops it and uku- contracts (ukwahlula, ukoyika).
            stem = seed[1:]
            return ("uk" if stem.startswith("o") else "ukw") + stem
        return "uku" + seed
    return seed


def resolve(verbs: str, joiner: str) -> list[Row]:
    """Apply the decision flags to SELECTIONS and return the chosen rows."""
    rows = []
    for category, name, seed, word_type, confidence, rationale in SELECTIONS:
        words = separated(word_type, seed, verbs)
        value = surface(words, joiner)
        default_words = separated(word_type, seed, DEFAULTS["verbs"])
        recommended = surface(default_words, DEFAULTS["joiner"])
        rationale += separated_note(default_words)
        if value != recommended:
            flags = ", ".join(
                f"--{flag} {choice}"
                for flag, choice in (("verbs", verbs), ("joiner", joiner))
                if choice != DEFAULTS[flag]
                and (flag != "joiner" or "_" in words.strip("_"))
                and (flag != "verbs" or words != default_words)
            )
            rationale = branch_rationale(flags, recommended, words, rationale)
        rows.append((category, name, value, word_type, confidence, rationale))
    return rows


