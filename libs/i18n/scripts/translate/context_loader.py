"""Context and linguistic standards loaders for translation pipeline.

This module loads deep context documents (from CORE-393) and linguistic
standards to provide rich context for AI translations.
"""

import json
import logging
from pathlib import Path
from typing import Dict, Optional

logger = logging.getLogger(__name__)


class ContextLoader:
    """Loads deep context documents for Python terms.

    Deep context documents provide etymology, explanations, and translation
    guidance for each Python term. These are generated by CORE-393.
    """

    def __init__(self, context_dir: Optional[Path] = None):
        """Initialize context loader.

        Args:
            context_dir: Directory containing context documents
                        (defaults to libs/i18n/context/python/)
        """
        if context_dir is None:
            # Default to standard location
            self.context_dir = (
                Path(__file__).parent.parent.parent / "context" / "python"
            )
        else:
            self.context_dir = Path(context_dir)

        self._context_cache: Dict[str, str] = {}
        logger.info(f"Context loader initialized: {self.context_dir}")

    def load_context(self, term: str) -> Optional[str]:
        """Load deep context document for a term.

        Args:
            term: Python term (e.g., "def", "return", "print")

        Returns:
            Context document content as string, or None if not found
        """
        # Check cache first
        if term in self._context_cache:
            return self._context_cache[term]

        # Try to load from file
        context_file = self.context_dir / f"{term}.md"

        if not context_file.exists():
            logger.warning(
                f"No context document found for term '{term}' at {context_file}"
            )
            return None

        try:
            with open(context_file, "r", encoding="utf-8") as f:
                content = f.read()

            # Cache it
            self._context_cache[term] = content
            logger.debug(f"Loaded context for '{term}' ({len(content)} chars)")
            return content

        except Exception as e:
            logger.error(f"Error loading context for '{term}': {e}")
            return None

    def get_term_list(self) -> list[str]:
        """Get list of all terms that have context documents.

        Returns:
            List of term names (without .md extension)
        """
        if not self.context_dir.exists():
            logger.warning(f"Context directory does not exist: {self.context_dir}")
            return []

        terms = [
            f.stem
            for f in self.context_dir.glob("*.md")
            if f.is_file() and not f.name.startswith("_")
        ]

        logger.info(f"Found {len(terms)} context documents")
        return sorted(terms)

    def preload_all(self):
        """Preload all context documents into cache."""
        terms = self.get_term_list()
        logger.info(f"Preloading {len(terms)} context documents...")

        loaded_count = 0
        for term in terms:
            if self.load_context(term):
                loaded_count += 1

        logger.info(f"Preloaded {loaded_count}/{len(terms)} context documents")


class LinguisticStandardsLoader:
    """Loads linguistic standards for target languages.

    Linguistic standards define language-specific translation conventions
    (grammatical forms, word choices, etc.) for each target language.
    """

    def __init__(self, standards_file: Optional[Path] = None):
        """Initialize linguistic standards loader.

        Args:
            standards_file: Path to linguistic-standards.md file
                           (defaults to libs/i18n/docs/linguistic-standards.md)
        """
        if standards_file is None:
            # Default to standard location
            self.standards_file = (
                Path(__file__).parent.parent.parent / "docs" / "linguistic-standards.md"
            )
        else:
            self.standards_file = Path(standards_file)

        self._standards_cache: Dict[str, str] = {}
        self._standards_content: Optional[str] = None
        logger.info(f"Linguistic standards loader initialized: {self.standards_file}")

    def load_standards(self, language_code: str) -> Optional[str]:
        """Load linguistic standards for a specific language.

        Args:
            language_code: Language code (e.g., "es", "ar", "zh")

        Returns:
            Standards section for that language, or None if not found
        """
        # Check cache first
        if language_code in self._standards_cache:
            return self._standards_cache[language_code]

        # Load full standards file if not loaded
        if self._standards_content is None:
            if not self.standards_file.exists():
                logger.warning(
                    f"Linguistic standards file not found: {self.standards_file}"
                )
                return None

            try:
                with open(self.standards_file, "r", encoding="utf-8") as f:
                    self._standards_content = f.read()
            except Exception as e:
                logger.error(f"Error loading linguistic standards: {e}")
                return None

        # Extract section for this language
        # Format: ## Spanish (es) ... next ## heading
        import re

        # Map codes to full names
        LANGUAGE_FULL_NAMES = {
            "es": "Spanish",
            "ar": "Arabic",
            "fr": "French",
            "zh": "Chinese",
            "hi": "Hindi",
            "ru": "Russian",
            "pt": "Portuguese",
            "de": "German",
            "ja": "Japanese",
            "ko": "Korean",
            "it": "Italian",
            "pl": "Polish",
            "tr": "Turkish",
            "vi": "Vietnamese",
            "th": "Thai",
            "nl": "Dutch",
            "sv": "Swedish",
            "no": "Norwegian",
            "da": "Danish",
            "fi": "Finnish",
            "el": "Greek",
            "he": "Hebrew",
            "id": "Indonesian",
            "ms": "Malay",
        }

        language_name = LANGUAGE_FULL_NAMES.get(language_code, language_code.upper())

        # Try to find section like "## Spanish (es)" or "## Spanish"
        pattern = rf"##\s+{language_name}\s*\(.*?\)|##\s+{language_name}\s*$"
        match = re.search(
            pattern, self._standards_content, re.MULTILINE | re.IGNORECASE
        )

        if not match:
            logger.warning(
                f"No standards found for language '{language_code}' ({language_name})"
            )
            return None

        # Extract content from this heading to next ## heading
        start_pos = match.end()
        next_heading = re.search(r"\n##\s+", self._standards_content[start_pos:])

        if next_heading:
            end_pos = start_pos + next_heading.start()
            section = self._standards_content[start_pos:end_pos]
        else:
            # Last section in file
            section = self._standards_content[start_pos:]

        # Cache it
        self._standards_cache[language_code] = section.strip()
        logger.debug(f"Loaded standards for '{language_code}' ({len(section)} chars)")

        return self._standards_cache[language_code]

    def get_supported_languages(self) -> list[str]:
        """Get list of languages that have standards defined.

        Returns:
            List of language codes
        """
        if self._standards_content is None:
            if not self.standards_file.exists():
                return []

            try:
                with open(self.standards_file, "r", encoding="utf-8") as f:
                    self._standards_content = f.read()
            except Exception as e:
                logger.error(f"Error loading linguistic standards: {e}")
                return []

        # Find all language sections
        import re

        pattern = r"##\s+(\w+)\s+\(([a-z]{2})\)"
        matches = re.findall(pattern, self._standards_content, re.MULTILINE)

        language_codes = [code for _, code in matches]
        logger.info(
            f"Found standards for {len(language_codes)} languages: {language_codes}"
        )

        return language_codes


def load_term_manifest(manifest_path: Optional[Path] = None) -> Dict:
    """Load Python terms manifest (from CORE-393).

    The manifest contains metadata about all Python terms including
    complexity levels and categorization.

    Args:
        manifest_path: Path to manifest JSON file
                      (defaults to libs/i18n/data/python-terms-manifest.json)

    Returns:
        Manifest dictionary with term metadata
    """
    if manifest_path is None:
        manifest_path = (
            Path(__file__).parent.parent.parent / "data" / "python-terms-manifest.json"
        )

    if not manifest_path.exists():
        logger.warning(f"Term manifest not found: {manifest_path}")
        return {"terms": []}

    try:
        with open(manifest_path, "r", encoding="utf-8") as f:
            manifest = json.load(f)

        logger.info(f"Loaded term manifest with {len(manifest.get('terms', []))} terms")
        return manifest

    except Exception as e:
        logger.error(f"Error loading term manifest: {e}")
        return {"terms": []}
