def resolve(joiner: str) -> list[Row]:
    """Apply the joiner flag to SELECTIONS and return the chosen rows."""
    rows = []
    for category, name, words, word_type, confidence, rationale in SELECTIONS:
        value = surface(words, joiner)
        recommended = surface(words, "none")
        rationale += separated_note(words)
        if value != recommended:
            rationale = branch_rationale(
                "--joiner underscore", recommended, words, rationale
            )
        rows.append((category, name, value, word_type, confidence, rationale))
    return rows


