"""YAML export functionality for translation pipeline.

This module exports translations from the database to YAML format
compatible with the Legesher language pack structure.

Exports to hierarchical format:
  language-packs/python/{lang}/legesher_i18n_python_{lang}/packs/3.10.yml

CORE-1400 contract — pack regeneration is safe because:

- The ONLY data source is ``selected_translations`` (the canonical,
  publish-gated layer). The dirty-tolerant candidate pool
  (``translations``) is never read here; choosing among candidates is
  the selection rule's job (``legesher_i18n/selection.py``,
  ``docs/translation-selection.md``).
- Pack section content is rewritten *authoritatively*: terms can be
  added, removed, and relocated. There is no merge-with-existing-file
  union step.
- A pack is only written when the language's selections are COMPLETE
  for the term inventory (pinned to ``legesher_i18n.term_definitions``,
  which the stdlib-baseline guard reconciles against the interpreter).
  Incomplete languages are skipped (or raise, in strict mode) — partial
  packs are never emitted, so a half-translated language can never
  clobber a shipped pack.
- ``implicit_params`` (``self``/``cls``) is a first-class section and
  survives rewrites; the dual-slot ``type`` term (3.10 builtin vs 3.12
  soft keyword) exports each slot from its own term row.
- The vocabulary partition (``symbols`` / ``variable_conventions``,
  CORE-1396) reads ``selected_vocabulary`` instead, rides the 3.10 base
  file, and is OPTIONAL — a language with none exports exactly as it did
  before the partition existed. A section that is present but incomplete
  is skipped with a warning rather than emitted half-filled.
- Existing file header comments, metadata, and key order are preserved;
  ``metadata.last_updated`` only changes when section content changed.
- An existing pack file that cannot be parsed, or does not parse to a
  mapping, is never rewritten (:class:`UnparseablePackError`). Because
  the rewrite is authoritative, treating an unreadable file as empty
  would silently reset the curated metadata block — license,
  ``python_version_min`` (the interpreter floor itself),
  ``community_reviewed`` — to generated defaults. All five version files
  are read BEFORE any of them is written, so one bad file can never
  leave a half-rewritten pack directory behind.
- Interpreter-floor tiering (CORE-1521) never fabricates a collision:
  if stripping 3.13-only XID characters would collapse two DIFFERENT
  terms onto one token in the pre-3.13 packs, the export raises
  (:class:`InterpreterFloorCollisionError`) instead of emitting a pack
  that is no longer reversible on 3.10-3.12. Like the DB-side guard, it
  groups by term NAME: the dual-slot ``type`` term is one surface token
  in two sections, not two colliding terms.
- Tiering only ever DELETES a character, so it is restricted to the
  characters whose deletion leaves the same word (ZWJ, ZWNJ, the two
  katakana middle dots). A value needing any other member of the
  3.10 -> 3.13 XID delta raises :class:`UnstrippableXIDError` rather
  than being silently mangled into a different word.
- A bulk run reports EVERY language it could not export
  (:class:`BulkExportError`, raised at the end) rather than aborting on
  the first, so which packs a run produces never depends on where the
  bad language sorts alphabetically. Data-integrity failures rank above
  environmental ones (``OSError``: a directory in the file's place, a
  permission bit), and a language that RAISED for either reason fails
  the run — reporting success over a stale pack is the worse outcome.
  One deliberate exception: on the non-strict path a language with
  incomplete selections is skipped with a warning, not raised; the regen
  gate's ``not_regenerated`` finding is the blocking backstop for that
  skip (scripts/verify_pack_regen.py).
- Packaging files (pyproject.toml / README / CHANGELOG / __init__.py)
  are NOT regenerated by default (YAML-only export). When packaging is
  requested — for onboarding a new language — only *missing* files are
  created, and the generated pyproject is uv-workspace-safe (no
  ``[tool.uv.sources]`` override, no version reset).
"""

