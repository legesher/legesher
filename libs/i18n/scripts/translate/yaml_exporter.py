# Categories tried, in order, when resolving a builtins-section slot.
_BUILTIN_CATEGORIES = ("builtin_func", "builtin_type", "special_constant")

# Characters that are valid identifier chars only on CPython 3.13+
# (Unicode 15.1 XID) — the Sinhala-ZWJ trap. Mirrors
# SchemaValidator._XID_ONLY_FROM_CPYTHON_313. Canonical values containing
# these are exported version-tiered (CORE-1521): the pre-3.13 files carry
# the stripped compatibility form; the 3.13 overlay restores the canonical
# conjunct spelling.
_XID_ONLY_FROM_CPYTHON_313 = frozenset({"\u200d", "\u200c"})
_XID_STRIP_TABLE = {ord(ch): None for ch in _XID_ONLY_FROM_CPYTHON_313}

# Pack sections, in emitted file order.
_PACK_SECTIONS = ("keywords", "builtins", "exceptions", "reserved_words")


class IncompleteSelectionError(ValueError):
    """A pack-shipping language is missing canonical selections."""


class CorruptSelectionError(ValueError):
    """A canonical selection fails the publish gate the DB layer enforces.

    The most severe failure this module names: ``set_selected`` rejects
    such a value, so seeing one back means the selection layer itself is
    damaged. Ranked with the other data-integrity failures, never
    swallowed as per-language flakiness.
    """


class UnparseablePackError(ValueError):
    """An existing pack file cannot be parsed, so it must not be rewritten."""


class InterpreterFloorCollisionError(ValueError):
    """Interpreter-floor stripping would collapse two distinct terms."""


# Failures that mean the DATA is wrong. Ranked above everything else a
# language can raise (see :class:`BulkExportError`).
_DATA_INTEGRITY_FAILURES = (
    CorruptSelectionError,
    IncompleteSelectionError,
    InterpreterFloorCollisionError,
    UnparseablePackError,
)


class BulkExportError(ValueError):
    """A bulk run could not export one or more languages.

    Raised by :meth:`YAMLExporter.export_all_languages` AFTER every other
    language has been exported. Aborting on the first bad language would
    make the blast radius alphabetical — a corrupt ``am`` would drop all
    51 packs, a corrupt ``zh`` only one — while each language is already
    written atomically, so continuing costs nothing in safety.

    Failures are ranked, not flattened: :attr:`data_integrity` means the
    data is wrong, :attr:`environmental` (``OSError`` and friends) means
    the machine was. Both belong here. An environmental blip is the
    milder diagnosis, but the pack it skipped is just as stale as one a
    corrupt file skipped, and a caller that is only told in a log line
    goes on to report success over it.

    Attributes:
        failures: language code -> the exception that language raised,
            data-integrity failures first in the rendered message.
    """

    def __init__(self, failures: dict[str, Exception]):
        self.failures = dict(failures)
        detail = "; ".join(
            f"{lang}: {type(exc).__name__}: {exc}"
            for lang, exc in sorted(
                self.failures.items(),
                key=lambda item: (
                    not isinstance(item[1], _DATA_INTEGRITY_FAILURES),
                    item[0],
                ),
            )
        )
        super().__init__(
            f"{len(self.failures)} language(s) could not be exported: {detail}"
        )

    @property
    def data_integrity(self) -> dict[str, Exception]:
        """The failures that mean a pack's data is wrong."""
        return {
            lang: exc
            for lang, exc in self.failures.items()
            if isinstance(exc, _DATA_INTEGRITY_FAILURES)
        }

    @property
    def environmental(self) -> dict[str, Exception]:
        """The rest — ``OSError`` and friends: the machine, not the data."""
        return {
            lang: exc
            for lang, exc in self.failures.items()
            if not isinstance(exc, _DATA_INTEGRITY_FAILURES)
        }


class YAMLExporter:
    """Exports selected translations to YAML language packs.

    Authoritative, selection-sourced rewrite — see the module docstring
    for the CORE-1400 safety contract.
    """

    def __init__(self, db: TranslationDatabase, output_dir: Path | str | None = None):
        """Initialize YAML exporter.

        Args:
            db: Translation database instance
            output_dir: Output directory for YAML files
                       (defaults to libs/i18n/language-packs/python/)
        """
        self.db = db
        if output_dir is None:
            self.output_dir = (
                Path(__file__).parent.parent.parent / "language-packs" / "python"
            )
        else:
            self.output_dir = Path(output_dir)

        self.output_dir.mkdir(parents=True, exist_ok=True)
        logger.info(f"YAML exporter initialized: {self.output_dir}")

    # ------------------------------------------------------------------
    # Selection loading
    # ------------------------------------------------------------------

    def _load_selected_slots(self, language_code: str) -> dict[tuple[str, str], str]:
        """Load canonical selections as a (category, term_name) -> value map.

        Raises:
            CorruptSelectionError: If any selected value fails the publish
                gate (should be impossible — ``set_selected`` enforces it —
                but export must never propagate a dirty value).
        """
        slots: dict[tuple[str, str], str] = {}
        invalid: list[str] = []
        for row in self.db.get_all_selected(language_code=language_code):
            if row.get("programming_language") not in (None, "python"):
                continue
            name = row["term_name"]
            value = row["translation"]
            if not is_valid_pack_value(name, value):
                invalid.append(f"{name} -> {value!r}")
                continue
            slots[(row["term_category"], name)] = value
        if invalid:
            raise CorruptSelectionError(
                f"Selected translations for '{language_code}' fail the "
                f"publish gate (selection layer corrupt?): {invalid}"
            )
        return slots

    def _resolve_section_slots(
        self,
        slots: dict[tuple[str, str], str],
        section: str,
        term_names: list[str],
        missing: list[str],
    ) -> dict[str, str]:
        """Resolve pack-section values for ``term_names`` from selections."""
        resolved: dict[str, str] = {}
        for name in term_names:
            if section == "keywords":
                categories = ("keyword",)
            elif section == "builtins":
                categories = _BUILTIN_CATEGORIES
            elif section == "exceptions":
                categories = ("exception",)
            else:  # reserved_words
                categories = ("reserved_word",)

            for category in categories:
                if (category, name) in slots:
                    resolved[name] = slots[(category, name)]
                    break
            else:
                missing.append(f"{section}.{name}")
        return resolved

    def _build_version_sections(
        self,
        language_code: str,
        slots: dict[tuple[str, str], str],
        missing: list[str],
    ) -> dict[str, dict[str, dict[str, str]]]:
        """Resolve every version slot and apply interpreter-floor tiering.

        Returns ``{version: {section: {term: value}}}`` — the exact
        section payload each pack file gets. The section *keys* present
        per version are load-bearing: ``_write_yaml_pack`` emits an empty
        ``keywords``/``exceptions`` stub for a new file but never
        introduces ``builtins``/``reserved_words`` stubs, so 3.11/3.12/3.14
        deliberately carry only the two sections they can contain.

        Every slot is resolved BEFORE anything is written: a partial pack
        must never reach disk (the pre-CORE-1400 "3-term rewrite" bug
        class). Unresolved slots are appended to ``missing`` and an empty
        mapping is returned — the caller chooses strict failure or skip.

        Interpreter-floor tiering (CORE-1521): canonical values that use
        3.13-only XID characters (Sinhala ZWJ conjuncts) are written in
        stripped compatibility form in the pre-3.13 files, and the 3.13
        overlay restores the canonical spelling.

        Raises:
            InterpreterFloorCollisionError: If stripping collapses two
                canonically-distinct values into one token.
        """
        kw_310 = self._resolve_section_slots(
            slots, "keywords", KEYWORDS_BASE + SPECIAL_VALUES + KEYWORDS_3_10, missing
        )
        builtins_310 = self._resolve_section_slots(
            slots,
            "builtins",
            BUILTIN_FUNCTIONS + BUILTIN_TYPES + SPECIAL_CONSTANTS,
            missing,
        )
        exceptions_310 = self._resolve_section_slots(
            slots, "exceptions", EXCEPTIONS, missing
        )
        reserved_310 = self._resolve_section_slots(
            slots, "reserved_words", RESERVED_WORDS, missing
        )
        kw_311 = self._resolve_section_slots(slots, "keywords", KEYWORDS_3_11, missing)
        exceptions_311 = self._resolve_section_slots(
            slots, "exceptions", EXCEPTIONS_3_11, missing
        )
        kw_312 = self._resolve_section_slots(slots, "keywords", KEYWORDS_3_12, missing)
        exceptions_313 = self._resolve_section_slots(
            slots, "exceptions", EXCEPTIONS_3_13, missing
        )

        if missing:
            return {}

        overlay_313: dict[str, dict[str, str]] = {s: {} for s in _PACK_SECTIONS}
        # Emitted pre-3.13 value -> {"section.term": (term name, canonical)}.
        # A value reached by two DIFFERENT term names whose canonical
        # spellings differ is a collision stripping fabricated (see below).
        stripped_index: dict[str, dict[str, tuple[str, str]]] = {}

        def tier(section: str, values: dict[str, str]) -> dict[str, str]:
            tiered: dict[str, str] = {}
            for name, value in values.items():
                if any(ch in _XID_ONLY_FROM_CPYTHON_313 for ch in value):
                    overlay_313[section][name] = value
                    tiered[name] = value.translate(_XID_STRIP_TABLE)
                else:
                    tiered[name] = value
                stripped_index.setdefault(tiered[name], {})[f"{section}.{name}"] = (
                    name,
                    value,
                )
            return tiered

        # ``tier`` is called exactly for the pre-3.13 files, so
        # ``stripped_index`` covers every value a 3.10-3.12 interpreter sees
        # (the packs chain by ``extends``, so their sections share one
        # token namespace).
        sections: dict[str, dict[str, dict[str, str]]] = {
            "3.10": {
                "keywords": tier("keywords", kw_310),
                "builtins": tier("builtins", builtins_310),
                "exceptions": tier("exceptions", exceptions_310),
                "reserved_words": tier("reserved_words", reserved_310),
            },
            "3.11": {
                "keywords": tier("keywords", kw_311),
                "exceptions": tier("exceptions", exceptions_311),
            },
            "3.12": {"keywords": tier("keywords", kw_312), "exceptions": {}},
            "3.13": {
                "keywords": overlay_313["keywords"],
                "builtins": overlay_313["builtins"],
                "exceptions": {**exceptions_313, **overlay_313["exceptions"]},
                "reserved_words": overlay_313["reserved_words"],
            },
            "3.14": {"keywords": {}, "exceptions": {}},
        }

        self._assert_no_strip_collisions(language_code, stripped_index)
        return sections

    @staticmethod
    def _assert_no_strip_collisions(
        language_code: str, stripped_index: dict[str, dict[str, tuple[str, str]]]
    ):
        """Raise if ZWJ stripping made two DIFFERENT terms collide.

        The collision guards upstream (``db.find_collisions``,
        ``audit_collisions.py``) compare CANONICAL values, so they cannot
        see this: ``a<ZWJ>b`` and ``ab`` are distinct canonically and
        identical once stripped. Two different terms sharing one token
        make the pre-3.13 packs irreversible.

        Grouped by term NAME, matching the DB-side collision model this
        ticket settled on (``db.find_collisions``): the dual-slot ``type``
        term — 3.10 builtin and 3.12 soft keyword — occupies two sections
        but is ONE surface token, so its two slots landing on one stripped
        spelling is not a round-trip ambiguity. 22 of the 51 shipped packs
        already spell those two slots differently; keying on
        ``section.name`` would block every one of them that adopts a
        conjunct spelling for a single slot.

        Only stripping can trigger this — without it the emitted value is
        the canonical one, so equal emitted values imply equal canonical
        values. Values that already collide before stripping are a
        different (upstream) defect and are left to the gates that own it.
        """
        collisions = {
            value: locations
            for value, locations in stripped_index.items()
            if len({name for name, _ in locations.values()}) > 1
            and len({canonical for _, canonical in locations.values()}) > 1
        }
        if not collisions:
            return
        detail = "; ".join(
            f"{value!r} <- "
            + ", ".join(
                f"{loc} ({canonical!r})" for loc, (_, canonical) in sorted(locs.items())
            )
            for value, locs in sorted(collisions.items())
        )
        raise InterpreterFloorCollisionError(
            f"Interpreter-floor stripping (CORE-1521) would collapse two "
            f"DIFFERENT terms for '{language_code}' onto one token in the "
            f"pre-3.13 packs: {detail}. Give those terms spellings that stay "
            f"distinct once ZWJ/ZWNJ is removed — a stripped pack must stay "
            f"reversible on 3.10-3.12."
        )

    # ------------------------------------------------------------------
    # Export
    # ------------------------------------------------------------------

    def export_language(
        self,
        language_code: str,
        overwrite: bool = False,
        strict: bool = True,
        include_packaging: bool = False,
    ) -> Path | None:
        """Export a language's canonical selections to its pack structure.

        Creates/rewrites:
          {lang}/
            legesher_i18n_python_{lang}/
              packs/
                3.10.yml  (base pack: keywords, builtins, exceptions,
                           reserved_words)
                3.11.yml  (extends 3.10: except*, exception groups)
                3.12.yml  (extends 3.11: type soft keyword)
                3.13.yml  (extends 3.12: PythonFinalizationError)
                3.14.yml  (extends 3.13)

        Args:
            language_code: Language code (e.g., 'es', 'ar')
            overwrite: If False, skip languages whose pack directory
                already exists (legacy skip semantics). If True, rewrite
                the pack files authoritatively.
            strict: If True, raise :class:`IncompleteSelectionError` when
                the language's selections don't cover the full term
                inventory. If False, log a warning and skip the language
                (nothing is written — partial packs are never emitted).
            include_packaging: If True, create MISSING packaging files
                (__init__.py, pyproject.toml, README.md, CHANGELOG.md)
                for new-language onboarding. Existing packaging files are
                never overwritten.

        Returns:
            Path to the language pack directory, or None if skipped.

        Nothing is written until every slot is resolved AND all five
        existing version files are parsed, so each failure below happens
        with the pack directory untouched — a bad ``3.12.yml`` can never
        leave ``3.10.yml`` and ``3.11.yml`` rewritten and re-dated.

        Raises:
            CorruptSelectionError: When a canonical selection fails the
                publish gate.
            IncompleteSelectionError: In strict mode, when selections
                don't cover the full term inventory.
            InterpreterFloorCollisionError: When interpreter-floor
                stripping would collapse two different terms.
            UnparseablePackError: When an existing pack file cannot be
                parsed back, so rewriting it would destroy curated
                metadata.
        """
        lang_dir = self.output_dir / language_code
        pack_name = f"legesher_i18n_python_{language_code}"
        packs_dir = lang_dir / pack_name / "packs"

        if lang_dir.exists() and not overwrite:
            logger.info(f"Language pack {language_code} already exists, skipping")
            return lang_dir

        slots = self._load_selected_slots(language_code)
        if not slots:
            logger.warning(f"No selected translations for language '{language_code}'")
            return None

        missing: list[str] = []
        sections = self._build_version_sections(language_code, slots, missing)

        if missing:
            message = (
                f"Language '{language_code}' has no canonical selection for "
                f"{len(missing)} term slot(s): {sorted(missing)[:10]}"
                f"{' ...' if len(missing) > 10 else ''}. "
                f"Select values (see docs/translation-selection.md) before "
                f"exporting; partial packs are never written."
            )
            if strict:
                raise IncompleteSelectionError(message)
            logger.warning(message + " Skipping language.")
            return None

        lang_name = get_language_name(language_code)
        # (file, version, extends, header used only for a file created
        # from scratch), in emitted order.
        plan = [
            (
                packs_dir / "3.10.yml",
                "3.10",
                None,
                f"# {lang_name} Language Pack for Python 3.10+\n"
                f"# Base pack with all core keywords and Python 3.10 additions"
                f" (match/case, aiter/anext)\n"
                f"# Generated by Legesher Translation Pipeline\n\n",
            ),
            (
                packs_dir / "3.11.yml",
                "3.11",
                "3.10.yml",
                f"# {lang_name} Language Pack for Python 3.11+\n"
                f"# Extends 3.10 pack and adds except* for exception groups\n\n",
            ),
            (
                packs_dir / "3.12.yml",
                "3.12",
                "3.11.yml",
                f"# {lang_name} Language Pack for Python 3.12+\n"
                f"# Extends 3.11 pack and adds 'type' keyword for type parameters\n\n",
            ),
            (
                packs_dir / "3.13.yml",
                "3.13",
                "3.12.yml",
                f"# {lang_name} Language Pack for Python 3.13+\n"
                f"# Extends 3.12 pack and adds PythonFinalizationError\n\n",
            ),
            (
                packs_dir / "3.14.yml",
                "3.14",
                "3.13.yml",
                f"# {lang_name} Language Pack for Python 3.14+\n"
                f"# Extends 3.13 pack (Python 3.14 in development)\n\n",
            ),
        ]
        # Same rule as slot resolution: resolve everything before writing
        # anything. Reading inside the write loop would let a bad 3.12.yml
        # raise with 3.10.yml and 3.11.yml already rewritten and re-dated.
        existing = [self._read_existing(filepath) for filepath, _, _, _ in plan]

        packs_dir.mkdir(parents=True, exist_ok=True)
        for (filepath, version, extends, default_header), prior in zip(
            plan, existing, strict=True
        ):
            self._write_yaml_pack(
                filepath,
                language_code,
                version,
                extends,
                sections[version],
                default_header,
                prior,
            )

        if include_packaging:
            # Distinct term NAMES unioned across every version file — the same
            # merge scripts/generate_reference_docs.py performs for REFERENCE.md,
            # so README.md and REFERENCE.md agree (CORE-1014); the 3.13 overlay
            # only restores canonical spellings, so names never double-count.
            def term_count(section: str) -> int:
                return len(
                    {
                        name
                        for version_sections in sections.values()
                        for name in version_sections.get(section, {})
                    }
                )

            counts = {
                "keywords": term_count("keywords"),
                "builtins": term_count("builtins"),
                "exceptions": term_count("exceptions"),
            }
            self._generate_packaging_files(language_code, lang_dir, pack_name, counts)

        logger.info(f"Exported language pack for '{language_code}' to {lang_dir}")
        return lang_dir

    # ------------------------------------------------------------------
    # Pack file writing (authoritative)
    # ------------------------------------------------------------------

    @staticmethod
    def _read_existing(filepath: Path) -> tuple[dict, str | None]:
        """Read an existing pack file: (parsed data, header comment block).

        A file that is absent (or empty) is genuinely new: it contributes
        nothing and the caller creates it from scratch. A file that EXISTS
        but cannot be read back as a mapping is a different situation
        entirely — because the rewrite is authoritative, treating it as
        empty would silently reset the curated metadata block (license,
        ``python_version_min`` — the interpreter floor itself,
        ``community_reviewed``) to generated defaults, and flip the
        new-file empty-section semantics mid-rewrite. Refuse instead.

        Raises:
            UnparseablePackError: If an existing file's CONTENT is not a
                YAML mapping in UTF-8. An ``OSError`` (permissions, a
                directory in the file's place, an I/O error) is left to
                propagate as itself: an environmental blip is not a
                data-integrity failure and must not be ranked as one. A
                bulk run still reports it — ranked below these, never
                dropped (:class:`BulkExportError`).
        """
        if not filepath.exists():
            return {}, None
        try:
            text = filepath.read_text(encoding="utf-8")
        except UnicodeDecodeError as e:
            raise UnparseablePackError(
                f"Refusing to rewrite {filepath}: the existing pack is not "
                f"valid UTF-8 ({e}). An authoritative rewrite would reset its "
                f"curated metadata to generated defaults. Repair or remove "
                f"the file, then re-export."
            ) from e

        try:
            data = yaml.safe_load(text) or {}
        except yaml.YAMLError as e:
            raise UnparseablePackError(
                f"Refusing to rewrite {filepath}: the existing pack is not "
                f"valid YAML ({e}). An authoritative rewrite would reset its "
                f"curated metadata to generated defaults. Repair or remove "
                f"the file, then re-export."
            ) from e
        if not isinstance(data, dict):
            raise UnparseablePackError(
                f"Refusing to rewrite {filepath}: the existing pack parses to "
                f"{type(data).__name__}, not a mapping. An authoritative "
                f"rewrite would reset its curated metadata to generated "
                f"defaults. Repair or remove the file, then re-export."
            )

        header_lines: list[str] = []
        for line in text.splitlines():
            if line.startswith("#") or (header_lines and not line.strip()):
                header_lines.append(line)
            else:
                break
        # An existing file with no leading comments keeps having none —
        # the default header is only for files created from scratch.
        header = "\n".join(header_lines) + "\n" if header_lines else ""
        if not header.endswith("\n\n") and header.strip():
            # Normalize to a blank line between header and document.
            header = header.rstrip("\n") + "\n\n"
        return data, header

    @staticmethod
    def _order_section(new_values: dict[str, str], existing: dict) -> dict[str, str]:
        """Order section keys: existing order first, new keys sorted after."""
        ordered: dict[str, str] = {}
        for key in existing or {}:
            if key in new_values:
                ordered[key] = new_values[key]
        for key in sorted(
            (k for k in new_values if k not in ordered), key=lambda k: str(k).lower()
        ):
            ordered[key] = new_values[key]
        return ordered

    def _write_yaml_pack(
        self,
        filepath: Path,
        language_code: str,
        version: str,
        extends: str | None,
        sections: dict[str, dict[str, str]],
        default_header: str,
        existing: tuple[dict, str | None],
    ):
        """Write a single YAML pack file, authoritatively.

        Section content comes entirely from ``sections`` — keys absent
        from it are REMOVED from the file (that's what makes relocation
        and retirement of terms possible). The existing file contributes
        only presentation and provenance: header comments, key order, and
        the metadata block. ``metadata.last_updated`` is refreshed only
        when section content actually changed.

        ``existing`` is the already-parsed ``_read_existing`` result for
        ``filepath``. It is a parameter rather than a call so that every
        version file of a pack is parsed before the first one is written.
        """
        existing_data, existing_header = existing

        yaml_data: dict = {
            "language": language_code,
            "target": "python",
            "version": version,
        }
        if extends:
            yaml_data["extends"] = extends

        content_changed = False
        # Non-empty sections are always emitted. Empty keywords/exceptions
        # are emitted as ``{}`` for new files (standard shape); for
        # existing files their presence follows the shipped file, so a
        # rewrite never introduces or drops empty-section stubs.
        file_exists = bool(existing_data)
        for section in _PACK_SECTIONS:
            new_values = sections.get(section, {})
            existing_section = existing_data.get(section) or {}
            if dict(existing_section) != new_values:
                content_changed = True
            emit_empty = (
                section in existing_data
                if file_exists
                else section in ("keywords", "exceptions")
            )
            if new_values or emit_empty:
                yaml_data[section] = self._order_section(new_values, existing_section)

        existing_metadata = existing_data.get("metadata", {}) or {}
        today = datetime.now().strftime("%Y-%m-%d")
        yaml_data["metadata"] = {
            "python_version_min": existing_metadata.get("python_version_min", version),
            "python_version_max": existing_metadata.get("python_version_max", "3.14"),
            "compatibility_tested": existing_metadata.get(
                "compatibility_tested", [version]
            ),
            "last_updated": (
                today
                if content_changed or "last_updated" not in existing_metadata
                else existing_metadata["last_updated"]
            ),
            "community_reviewed": existing_metadata.get("community_reviewed", False),
            "author": existing_metadata.get("author", "Legesher Team (Aya AI Model)"),
            "license": existing_metadata.get("license", "Apache-2.0"),
        }
        # Preserve any extra metadata keys a curator added by hand.
        for key, value in existing_metadata.items():
            yaml_data["metadata"].setdefault(key, value)

        header = existing_header if existing_header is not None else default_header

        # Written unconditionally, even when the bytes are unchanged.
        # ``verify_pack_regen.find_not_regenerated`` — the repo's own regen
        # gate — detects a pack the exporter never touched by comparing
        # mtimes against a pre-run sentinel, so a "skip the write if
        # nothing changed" optimization here would turn that gate into a
        # wall of false failures with every test still green. The rewrite
        # is byte-stable, so the write costs only the syscall.
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(header)
            yaml.dump(
                yaml_data,
                f,
                default_flow_style=False,
                allow_unicode=True,
                sort_keys=False,
            )

        logger.debug(f"Wrote {filepath}")

