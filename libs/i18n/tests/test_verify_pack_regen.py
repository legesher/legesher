def test_main_collapses_a_new_pack_layer_to_one_finding(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture
) -> None:
    """A future ``members`` landing must not print one line per pack.

    Ten shipped packs carry an unregistered top-level key; the exporter
    drops it from all ten. The class stays blocking — one line, not ten.
    """

    def add_members(shipped: Path) -> None:
        for f in shipped.rglob("*.yml"):
            f.write_text(
                f.read_text(encoding="utf-8") + "\nmembers:\n  push: empujar\n",
                encoding="utf-8",
            )

    def export(packs: Path):
        # The exporter rebuilds from a fixed key set: ``members`` is gone.
        _rewrite(
            packs,
            gate.EXPECTED_VERSIONS,
            lambda text: text.replace("\nmembers:\n  push: empujar\n", ""),
        )
        return packs

    assert (
        _run_gate(
            monkeypatch, tmp_path, export, ["en", "es"], mutate_shipped=add_members
        )
        == 1
    )
    out = capsys.readouterr().out
    assert "unknown_section: 1" in out
    assert "Blocking differences: 1" in out


def test_main_survives_an_export_that_raises(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture
) -> None:
    """A language that cannot be exported must not blank the report.

    ``export_language`` raises ``IncompleteSelectionError`` for a
    language whose selections do not cover the term inventory — live
    risk, since ``pack_languages()`` reads the disk and languages land
    there before every slot is selected. Unhandled, that traceback kills
    the run before the report is written: the earlier the language
    sorts, the more of the matrix it takes with it, and ``am`` sorts
    first.
    """
    report = tmp_path / "report.md"

    def export(packs: Path):
        if packs.parents[1].name == "am":
            raise RuntimeError("no canonical selection for 3 slot(s):\n['if', 'or']")
        return _faithful(packs)

    assert (
        _run_gate(
            monkeypatch,
            tmp_path,
            export,
            ["am", "en"],
            argv=["--report", str(report)],
        )
        == 1
    )
    out = capsys.readouterr().out
    assert "export_failed: 1" in out
    assert "am (all): export_failed" in out
    assert "RuntimeError: no canonical selection for 3 slot(s): ['if', 'or']" in out
    # The other language was still exported, compared and reported.
    assert "Pack files compared: 5 of 10 expected" in out
    assert "not_regenerated: 5" in out
    assert "export_failed" in report.read_text(encoding="utf-8")
    assert "export_failed" not in gate.INFORMATIONAL_KINDS


