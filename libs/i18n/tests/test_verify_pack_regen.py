def _shipped_tree(root: Path, langs: list[str]) -> Path:
    """Build a shipped-shaped pack tree: {lang}/legesher_i18n_python_{lang}/packs."""
    for lang in langs:
        _build_tree(
            root / lang / f"legesher_i18n_python_{lang}" / "packs",
            gate.EXPECTED_VERSIONS,
        )
    return root


