def test_a_real_export_clears_every_sentinel(tmp_path: Path) -> None:
    """Pin the cross-file coupling the whole sentinel rests on.

    ``find_not_regenerated`` is only sound because
    ``yaml_exporter._write_yaml_pack`` rewrites UNCONDITIONALLY, so a
    real export always advances the mtime. Every other ``main()`` case
    here drives a fake exporter, and the seed-clearing case below
    hand-rolls a write — none of them touch the real exporter, so a
    three-line "skip the write when the rendered text is unchanged"
    optimization would leave every sentinel set and make the gate report
    ``not_regenerated: 255`` on a pristine tree while the suite stayed
    green. Compose the two for real: shipped seed in, real export over
    it, sentinel check out.
    """
    scratch = tmp_path / "python"
    gate.seed_scratch(["es"], scratch)
    exporter = yaml_exporter.YAMLExporter(
        db=TranslationDatabase(db_path=str(gate.DB_PATH)), output_dir=scratch
    )
    assert exporter.export_language("es", overwrite=True, strict=True) is not None
    findings: list[dict] = []
    assert gate.find_not_regenerated(["es"], scratch, findings) == set()
    assert findings == []


def test_a_rewrite_clears_the_sentinel(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Any write advances the mtime, so a real export clears every flag."""
    monkeypatch.setattr(gate, "PACKS_DIR", _shipped_tree(tmp_path / "shipped", ["xx"]))
    scratch = tmp_path / "scratch"
    gate.seed_scratch(["xx"], scratch)
    for f in (scratch / "xx" / "legesher_i18n_python_xx" / "packs").glob("*.yml"):
        f.write_text(f.read_text(encoding="utf-8"), encoding="utf-8")
    findings: list[dict] = []
    assert gate.find_not_regenerated(["xx"], scratch, findings) == set()
    assert findings == []


