@pytest.mark.parametrize(
    "line,expected",
    [
        ("# leading comment", ["# leading comment"]),
        ("  # indented comment", ["# indented comment"]),
        ("keywords: {}  # trailing note", ["# trailing note"]),
        ("hash: '#not-a-comment'", []),
        ('hash: "#not-a-comment"', []),
        ("tag: value#notacomment", []),
        ("a: b  # first # second", ["# first # second"]),
        # A quote inside curator free text must not blind the scanner:
        # metadata is free text, and _write_yaml_pack preserves
        # hand-added metadata keys, so these lines are reachable in a
        # shipped pack. An apostrophe mid-scalar never opens a quoted
        # scalar, so it cannot hide the comment after it — including
        # when a second apostrophe makes the count EVEN, which is
        # exactly what a parity check gets wrong.
        (
            "  author: O'Brien  # hand-curated, do not auto-fill",
            ["# hand-curated, do not auto-fill"],
        ),
        ("  note: don't  # won't be regenerated", ["# won't be regenerated"]),
        ('  note: it"s odd  # still a comment', ["# still a comment"]),
        ("  author: O'Brien", []),
        ("  author: O'Brien#nothash", []),
        # Quoting only counts where a token may begin.
        ("hash: 'a#b' 'c#d'  # real", ["# real"]),
        ("  - '#not-a-comment'", []),
        ("  compatibility_tested: ['3.10', '#nope']  # list note", ["# list note"]),
        # A hyphen mid-word does not restart a token, so the quote after
        # it stays plain text and cannot swallow the comment.
        ("  note: well-known O'Brien  # kept", ["# kept"]),
    ],
)
def test_comments_of(line: str, expected: list[str]) -> None:
    assert gate._comments_of(line) == expected


#: (line, the value ``yaml.safe_load`` gives it, the comments on it).
#: The scanner's rule is "a quote opens a scalar only where a token may
#: begin"; these pin that rule against the real parser rather than
#: against the scanner's own assumptions.
YAML_PARITY_LINES: list[tuple[str, str, list[str]]] = [
    ("hash: '#not-a-comment'", "#not-a-comment", []),
    ('hash: "#not-a-comment"', "#not-a-comment", []),
    ("hash: '#quoted'  # and a real one", "#quoted", ["# and a real one"]),
    (
        "url: https://example.com/spec#anchor",
        "https://example.com/spec#anchor",
        [],
    ),
    (
        "url: https://example.com/spec#anchor  # see the spec",
        "https://example.com/spec#anchor",
        ["# see the spec"],
    ),
    ("if: إذا  # Arabic for 'if'", "إذا", ["# Arabic for 'if'"]),
    ("if: 'إذا # ليس تعليقًا'", "إذا # ليس تعليقًا", []),
    ("note: don't # won't", "don't", ["# won't"]),
    ("author: O'Brien  # x", "O'Brien", ["# x"]),
]


@pytest.mark.parametrize(
    "line,value,expected",
    YAML_PARITY_LINES,
    ids=[
        "single_quoted_hash",
        "double_quoted_hash",
        "quoted_hash_plus_real_comment",
        "url_fragment",
        "url_fragment_plus_comment",
        "arabic_value_with_comment",
        "arabic_quoted_hash",
        "even_apostrophe_count",
        "odd_apostrophe_count",
    ],
)
def test_comments_of_agrees_with_yaml_safe_load(
    line: str, value: str, expected: list[str]
) -> None:
    """The scanner and PyYAML must agree on where the scalar ends.

    Both halves are asserted: PyYAML confirms the line means what the
    case claims (so the expectation is not just the scanner's own
    opinion written twice), then the scanner must find exactly the
    comments PyYAML left out of the value.
    """
    key = line.split(":", 1)[0]
    assert yaml.safe_load(line) == {key: value}
    assert gate._comments_of(line) == expected


def test_apostrophe_does_not_launder_a_lost_comment(tmp_path: Path) -> None:
    """The false negative in full: loss reported, not hidden in bytes."""
    shipped = BASE_PACK.replace(
        "  license: MIT",
        "  license: MIT\n  author: O'Brien  # hand-curated, do not auto-fill",
    )
    regen = BASE_PACK.replace("  license: MIT", "  license: MIT\n  author: O'Brien")
    kinds = {f["kind"] for f in _findings(tmp_path, shipped, regen)}
    assert "comment_lost" in kinds


