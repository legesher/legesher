def _build_tree(root: Path, versions: tuple[str, ...]) -> Path:
    for version in versions:
        _write(root / f"{version}.yml", BASE_PACK.replace("'3.10'", f"'{version}'"))
    return root


def test_compare_language_counts_actual_comparisons(tmp_path: Path) -> None:
    shipped = _build_tree(tmp_path / "shipped", gate.EXPECTED_VERSIONS)
    regen = _build_tree(tmp_path / "regen", gate.EXPECTED_VERSIONS)
    findings: list[dict] = []
    compared = gate.compare_language("xx", shipped, regen, findings)
    assert compared == set(gate.EXPECTED_VERSIONS)
    assert findings == []


def test_missing_shipped_file_is_reported(tmp_path: Path) -> None:
    """The reproduced bug: a shipped file that no longer exists.

    Iterating only ``shipped_dir`` meant the file was simply never
    visited, so it could not produce a difference.
    """
    shipped = _build_tree(tmp_path / "shipped", ("3.10", "3.11", "3.13", "3.14"))
    regen = _build_tree(tmp_path / "regen", gate.EXPECTED_VERSIONS)
    findings: list[dict] = []
    compared = gate.compare_language("xx", shipped, regen, findings)
    assert "3.12" not in compared
    assert [(f["kind"], f["version"]) for f in findings] == [("file_added", "3.12")]
    assert "file_added" not in gate.INFORMATIONAL_KINDS


def test_missing_regen_file_is_reported(tmp_path: Path) -> None:
    shipped = _build_tree(tmp_path / "shipped", gate.EXPECTED_VERSIONS)
    regen = _build_tree(tmp_path / "regen", ("3.10", "3.11", "3.12", "3.13"))
    findings: list[dict] = []
    compared = gate.compare_language("xx", shipped, regen, findings)
    assert "3.14" not in compared
    assert [(f["kind"], f["version"]) for f in findings] == [("file_missing", "3.14")]


def test_skipped_versions_are_not_counted_as_compared(tmp_path: Path) -> None:
    """A file already reported as ``not_regenerated`` is not evidence.

    Its scratch copy is the shipped file, so comparing it compares a file
    against itself — which is precisely the pass this gate must not give.
    """
    shipped = _build_tree(tmp_path / "shipped", gate.EXPECTED_VERSIONS)
    regen = _build_tree(tmp_path / "regen", gate.EXPECTED_VERSIONS)
    findings: list[dict] = []
    compared = gate.compare_language(
        "xx", shipped, regen, findings, skip_versions={"3.12"}
    )
    assert compared == set(gate.EXPECTED_VERSIONS) - {"3.12"}
    assert findings == []


def test_absent_shipped_directory_reports_every_file(tmp_path: Path) -> None:
    regen = _build_tree(tmp_path / "regen", gate.EXPECTED_VERSIONS)
    findings: list[dict] = []
    compared = gate.compare_language("xx", tmp_path / "missing", regen, findings)
    assert compared == set()
    assert {f["kind"] for f in findings} == {"file_added"}
    assert len(findings) == len(gate.EXPECTED_VERSIONS)


