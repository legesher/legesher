"""Tests for ``scripts/verify_pack_regen.py`` — the CORE-1400 regen gate.

This gate is the artifact the whole "regenerating the packs is safe"
claim rests on, so it needs tests of its own. The failure mode that
matters most is not a wrong diff, it is a gate that reports ``0
differences`` because it compared nothing: the original implementation
derived its headline count arithmetically (``len(langs) * 5``) and
iterated only the shipped files, so deleting pack files still produced a
green run. The ``compare_language`` / ``check_expected_matrix`` cases
below pin that shut.
"""

from __future__ import annotations

import sys
import textwrap
from pathlib import Path

import pytest
import yaml

# Add scripts directory to path for imports
sys.path.insert(0, str(Path(__file__).parent.parent / "scripts"))

import verify_pack_regen as gate  # noqa: E402

# ``verify_pack_regen`` puts scripts/translate on sys.path when imported.
import yaml_exporter  # noqa: E402
from legesher_i18n.db import TranslationDatabase  # noqa: E402

BASE_PACK = textwrap.dedent(
    """\
    # Test Language Pack for Python 3.10+
    # Generated by Legesher Translation Pipeline

    language: xx
    target: python
    version: '3.10'

    keywords:
      # curator note: PEP 634 structural pattern matching
      if: si
      else: sino

    builtins:
      print: imprimir

    metadata:
      license: MIT
      last_updated: '2026-01-01'
    """
)


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _findings(tmp_path: Path, shipped_text: str, regen_text: str) -> list[dict]:
    """Run ``compare_file`` over two pack texts and return the findings."""
    shipped = _write(tmp_path / "shipped" / "3.10.yml", shipped_text)
    regen = _write(tmp_path / "regen" / "3.10.yml", regen_text)
    findings: list[dict] = []
    gate.compare_file(shipped, regen, findings, "xx")
    return findings


def _kinds(tmp_path: Path, shipped_text: str, regen_text: str) -> set[str]:
    """Finding classes, minus the byte-level class.

    ``not_byte_identical`` fires for every mutation by construction, so
    excluding it keeps the table below about the classification under
    test. :func:`test_byte_difference_alone_is_informational` covers it.
    """
    return {
        f["kind"]
        for f in _findings(tmp_path, shipped_text, regen_text)
        if f["kind"] != "not_byte_identical"
    }


# ---------------------------------------------------------------------------
# compare_file classification
# ---------------------------------------------------------------------------

COMPARE_CASES: list[tuple[str, str, set[str]]] = [
    # (case id, regenerated text, expected finding classes)
    ("identical", BASE_PACK, set()),
    (
        "value_changed",
        BASE_PACK.replace("if: si", "if: cuando"),
        {"value_changed"},
    ),
    (
        "key_added",
        BASE_PACK.replace("  else: sino", "  else: sino\n  for: para"),
        {"key_added"},
    ),
    (
        "key_removed",
        BASE_PACK.replace("  else: sino\n", ""),
        {"key_removed"},
    ),
    (
        # Dropping a populated section is BOTH structural and a term
        # loss; the gate names each term rather than only the section.
        "populated_section_removed",
        BASE_PACK.replace("builtins:\n  print: imprimir\n", ""),
        {"section_changed", "key_removed"},
    ),
    (
        "scalar_field_changed",
        BASE_PACK.replace("version: '3.10'", "version: '3.11'"),
        {"section_changed"},
    ),
    (
        "metadata_changed",
        BASE_PACK.replace("license: MIT", "license: Apache-2.0"),
        {"metadata_changed"},
    ),
    (
        "header_changed",
        BASE_PACK.replace("# Test Language Pack for Python 3.10+\n", ""),
        {"header_changed", "comment_lost"},
    ),
    (
        "interior_comment_lost",
        BASE_PACK.replace(
            "  # curator note: PEP 634 structural pattern matching\n", ""
        ),
        {"comment_lost"},
    ),
    (
        "trailing_comment_lost",
        BASE_PACK.replace("  if: si", "  if: si  # inline curator note"),
        set(),  # regen GAINS a comment; only losses are reported
    ),
]


@pytest.mark.parametrize(
    "regen_text,expected",
    [(regen, expected) for _, regen, expected in COMPARE_CASES],
    ids=[case_id for case_id, _, _ in COMPARE_CASES],
)
def test_compare_file_classification(
    tmp_path: Path, regen_text: str, expected: set[str]
) -> None:
    assert _kinds(tmp_path, BASE_PACK, regen_text) == expected


def test_empty_section_stub_presence_is_structural(tmp_path: Path) -> None:
    """``exceptions: {}`` disappearing carries no terms but still fails.

    The exporter's empty-stub emission follows the shipped file, so a
    stub that appears or vanishes is a real regen behaviour change.
    """
    shipped = BASE_PACK + "\nexceptions: {}\n"
    assert _kinds(tmp_path, shipped, BASE_PACK) == {"section_changed"}


def test_shipped_trailing_comment_loss_is_reported(tmp_path: Path) -> None:
    """The real ``en`` 3.13/3.14 case: ``keywords: {} # ...`` loses its note."""
    shipped = BASE_PACK.replace("  if: si", "  if: si  # unchanged since 3.10")
    findings = _findings(tmp_path, shipped, BASE_PACK)
    lost = [f for f in findings if f["kind"] == "comment_lost"]
    assert len(lost) == 1
    assert "# unchanged since 3.10" in lost[0]["detail"]


def test_comment_lost_is_informational_not_blocking(tmp_path: Path) -> None:
    """Comment loss is reported, but does not fail the gate today.

    The exporter cannot yet round-trip interior comments, so promoting
    this to blocking would fail on the shipped tree. It must never be
    laundered back into ``not_byte_identical``, though.
    """
    regen = BASE_PACK.replace(
        "  # curator note: PEP 634 structural pattern matching\n", ""
    )
    findings = _findings(tmp_path, BASE_PACK, regen)
    assert "comment_lost" in {f["kind"] for f in findings}
    assert [f for f in findings if f["kind"] not in gate.INFORMATIONAL_KINDS] == []


def test_byte_difference_alone_is_informational(tmp_path: Path) -> None:
    """Reordered keys with identical values are representation-only."""
    regen = BASE_PACK.replace(
        "  if: si\n  else: sino", "  else: sino\n  if: si"
    ).replace("  # curator note: PEP 634 structural pattern matching\n", "")
    findings = _findings(tmp_path, BASE_PACK, regen)
    assert "not_byte_identical" in {f["kind"] for f in findings}
    assert [f for f in findings if f["kind"] not in gate.INFORMATIONAL_KINDS] == []


