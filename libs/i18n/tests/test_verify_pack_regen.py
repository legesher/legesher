def test_pack_outside_the_expected_matrix_is_blocking() -> None:
    """``compared - expected``: the direction that produced "260 of 255".

    A language directory absent from ``languages.json`` (live risk:
    translations.db carries more languages than the registry does) or a
    stray sixth version file used to pass with a self-contradicting
    coverage line.
    """
    compared = {("en", v) for v in gate.EXPECTED_VERSIONS} | {
        ("zz", "3.10"),
        ("en", "3.9"),
    }
    findings: list[dict] = []
    expected = gate.check_expected_matrix(["en"], compared, findings)
    assert {f["kind"] for f in findings} == {"unexpected_pack"}
    assert {(f["lang"], f["version"]) for f in findings} == {
        ("zz", "3.10"),
        ("en", "3.9"),
    }
    assert "unexpected_pack" not in gate.INFORMATIONAL_KINDS
    # The reported numerator can never exceed the denominator.
    assert len(compared & expected) <= len(expected)


def test_expected_versions_match_the_exporter(tmp_path: Path) -> None:
    """Guard the mirrored constant against exporter drift, behaviourally.

    Grepping the exporter source for ``packs_dir / "3.12.yml"`` broke on
    a cosmetic rewrite (``packs_dir.joinpath(...)``) while the gate was
    green, and it could not see the direction that matters most: a NEW
    version file the exporter starts emitting. Export a real language
    into a tmpdir and compare the filenames it actually produced.
    """
    exporter = yaml_exporter.YAMLExporter(
        db=TranslationDatabase(db_path=str(gate.DB_PATH)), output_dir=tmp_path
    )
    lang = "es"
    assert exporter.export_language(lang, overwrite=True, strict=True) is not None
    emitted = {
        f.stem
        for f in (tmp_path / lang / f"legesher_i18n_python_{lang}" / "packs").glob(
            "*.yml"
        )
    }
    assert emitted == set(gate.EXPECTED_VERSIONS)


def test_sections_match_the_exporter() -> None:
    """``SECTIONS`` mirrors ``_PACK_SECTIONS``; pin the mirror.

    The mirror is deliberate — ``unknown_section`` tells a contributor to
    register a new pack layer in BOTH places — but a mirror with no guard
    is just a copy waiting to drift.
    """
    assert gate.SECTIONS == yaml_exporter._PACK_SECTIONS


