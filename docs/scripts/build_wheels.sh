#!/usr/bin/env bash
#
# Build + vendor the pure-Python wheels the docs playground installs in-browser
# via Pyodide/micropip (CORE-1551). Outputs to docs/public/wheels/ alongside a
# pinned wheels-manifest.json that the runner reads (no runtime globbing).
#
# The playground runtime is Pyodide v314.0.2, which ships CPython 3.14 — so the
# language-pack loader auto-selects each pack's 3.14.yml. Every wheel here is
# py3-none-any (pure Python); pydantic/pyyaml/packaging come from the Pyodide
# package index at runtime, not from these files.
#
# These wheels are COMMITTED (see docs/.gitignore) so Vercel serves them as
# static assets. Re-run this script whenever core/i18n/packs change, then commit
# the regenerated docs/public/wheels/.
#
# Usage:  docs/scripts/build_wheels.sh
# Requires: uv (workspace build backend). No network needed.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOCS="$(cd "$HERE/.." && pwd)"
ROOT="$(cd "$DOCS/.." && pwd)"
OUT="$DOCS/public/wheels"

# RTL languages are out of scope for the v1 playground (the editor is LTR-only;
# RTL editing is tracked as CORE-1552). This set mirrors the rtl=true entries in
# the i18n language registry (legesher_i18n/language_registry.py).
RTL_EXCLUDE=(ar fa he ur)

is_rtl() {
  local l="$1" r
  for r in "${RTL_EXCLUDE[@]}"; do [ "$l" = "$r" ] && return 0; done
  return 1
}

cd "$ROOT"
rm -rf "$OUT"
mkdir -p "$OUT"

echo "building legesher-core + legesher-i18n wheels…"
uv build --package legesher-core --wheel -o "$OUT" >/dev/null
uv build --package legesher-i18n --wheel -o "$OUT" >/dev/null

echo "building non-RTL language-pack wheels…"
for d in "$ROOT"/libs/i18n/language-packs/python/*/; do
  lang="$(basename "$d")"
  is_rtl "$lang" && continue
  uv build --package "legesher-i18n-python-$lang" --wheel -o "$OUT" >/dev/null
done

# The playground installs wheels only — drop any stray sdists.
rm -f "$OUT"/*.tar.gz

# `uv build -o` drops a `.gitignore` (`*`) into the output dir to keep build
# artifacts out of git. Here the wheels are deliberately committed, so remove it
# (docs/.gitignore re-includes public/wheels/ over the root `wheels/` rule).
rm -f "$OUT/.gitignore"

echo "writing wheels-manifest.json…"
"${LEGESHER_PYTHON:-python3}" - "$OUT" <<'PY'
import json, re, sys
from pathlib import Path

out = Path(sys.argv[1])
wheels = sorted(p.name for p in out.glob("*.whl"))
core = next(w for w in wheels if w.startswith("legesher_core-"))
i18n = next(w for w in wheels if w.startswith("legesher_i18n-"))
packs = {}
for w in wheels:
    m = re.match(r"legesher_i18n_python_([a-z]+)-", w)
    if m:
        packs[m.group(1)] = w

manifest = {
    "_comment": "Generated by docs/scripts/build_wheels.sh — do not hand-edit. "
    "Pinned wheel filenames the playground worker installs via micropip.",
    "pyodide": "v314.0.2",
    "pythonTag": "3.14",
    "indexDeps": ["pyyaml", "pydantic", "packaging"],
    "core": core,
    "i18n": i18n,
    "packs": dict(sorted(packs.items())),
}
(out / "wheels-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
print(f"  core={core}")
print(f"  i18n={i18n}")
print(f"  packs={len(packs)} ({', '.join(sorted(packs))})")
PY

echo "done — vendored $(find "$OUT" -name '*.whl' | wc -l | tr -d ' ') wheels + manifest into $OUT"
